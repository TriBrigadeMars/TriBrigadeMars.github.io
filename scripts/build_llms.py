#!/usr/bin/env python3
"""Generate and validate the machine-readable layer of the portfolio site.

`index.html` is the single source of truth. This script renders it to clean
Markdown (`llms-full.txt`) so an assistant can load the whole page from one URL
instead of guessing structure from markup, and it validates that every relative
link in the hand-written `llms.txt` resolves to a real file.

Usage:
    python3 scripts/build_llms.py            # regenerate llms-full.txt
    python3 scripts/build_llms.py --check    # fail if llms-full.txt or links drift

Stdlib only, no network.
"""

import sys
from html.parser import HTMLParser
from pathlib import Path

ROOT = Path(__file__).resolve().parent.parent
PAGE = ROOT / "index.html"
FULL = ROOT / "llms-full.txt"
MANIFEST = ROOT / "llms.txt"

SITE = "https://tribrigademars.github.io/"

HEADER = f"""# Mars Cruz, MPH, CHES — full site content

> Generated from `index.html` by `scripts/build_llms.py`. Do not edit this file by hand:
> edit `index.html`, run `npm run build`, and let the build regenerate it.

Source: {SITE}
Site manual for agents: {SITE}llms.txt
Citation: "Mars Cruz, MPH, CHES — {SITE}"

---

"""

VOID = {
    "area", "base", "br", "col", "embed", "hr", "img", "input",
    "link", "meta", "param", "source", "track", "wbr",
}

# Chrome that is noise in a text rendering of the page.
SKIP_TAGS = {"script", "style", "svg", "nav", "button", "noscript", "head", "footer"}

HEADINGS = {"h1": "##", "h2": "###", "h3": "####", "h4": "#####"}

# Containers that own block-level layout. Anything else is inline content and is
# rendered as a paragraph when it appears on its own (chips, badge rows, links).
BLOCK_TAGS = {
    "h1", "h2", "h3", "h4", "p", "li", "ul", "ol", "blockquote",
    "div", "section", "main", "article", "header", "aside", "figure",
    "table", "thead", "tbody", "tr", "td", "th",
}


class Node:
    __slots__ = ("tag", "attrs", "children")

    def __init__(self, tag, attrs):
        self.tag = tag
        self.attrs = attrs
        self.children = []


class TreeBuilder(HTMLParser):
    def __init__(self):
        super().__init__(convert_charrefs=True)
        self.root = Node("#document", {})
        self.stack = [self.root]

    def handle_starttag(self, tag, attrs):
        node = Node(tag, dict(attrs))
        self.stack[-1].children.append(node)
        if tag not in VOID:
            self.stack.append(node)

    def handle_startendtag(self, tag, attrs):
        self.stack[-1].children.append(Node(tag, dict(attrs)))

    def handle_endtag(self, tag):
        for i in range(len(self.stack) - 1, 0, -1):
            if self.stack[i].tag == tag:
                del self.stack[i:]
                return

    def handle_data(self, data):
        self.stack[-1].children.append(data)


def squash(text):
    return " ".join(text.split())


def find(node, tag, attr=None, value=None):
    """First descendant (document order) matching tag and optional attribute."""
    for child in node.children:
        if not isinstance(child, Node):
            continue
        if child.tag == tag and (attr is None or child.attrs.get(attr) == value):
            return child
        found = find(child, tag, attr, value)
        if found is not None:
            return found
    return None


def inline(node):
    """Render inline content of a node to Markdown."""
    parts = []
    for child in node.children:
        if isinstance(child, str):
            parts.append(child)
            continue
        tag = child.tag
        if tag in SKIP_TAGS:
            continue
        if tag == "br":
            parts.append("\n")
        elif tag in ("strong", "b"):
            parts.append(f"**{inline(child).strip()}**")
        elif tag in ("em", "i"):
            inner = inline(child).strip()
            parts.append(f"*{inner}*" if inner else "")
        elif tag == "code":
            parts.append(f"`{inline(child).strip()}`")
        elif tag == "a":
            href = child.attrs.get("href", "")
            text = squash(inline(child))
            if not text:
                continue
            if href.startswith("mailto:"):
                parts.append(href[len("mailto:"):])
            elif href.startswith("http"):
                parts.append(f"[{text}]({href})")
            else:
                # Links to (PDF) assets or other local files keep their target;
                # in-page anchors would be meaningless in a single document.
                parts.append(f"[{text}]({href})" if not href.startswith("#") else text)
        elif child.tag in BLOCK_TAGS:
            # Block content inside an inline container (card links): separate
            # the blocks so their sentences do not run together.
            inner = inline(child)
            if inner:
                parts.append(f" {inner} ")
        else:
            parts.append(inline(child))
    return squash("".join(parts))


def has_block_child(node):
    return any(
        isinstance(child, Node)
        and child.tag not in SKIP_TAGS
        and (child.tag in BLOCK_TAGS or (child.tag == "a" and has_block_child(child)))
        for child in node.children
    )


def collect(node, out):
    """Walk the tree in document order, emitting (kind, text) blocks."""
    for child in node.children:
        if not isinstance(child, Node):
            continue
        tag = child.tag
        if tag in SKIP_TAGS:
            continue
        if tag in HEADINGS:
            text = squash(inline(child))
            if text:
                out.append((tag, text))
        elif tag == "p":
            text = inline(child)
            if text:
                out.append(("p", text))
        elif tag == "li":
            text = inline(child)
            if text:
                out.append(("li", text))
        elif tag == "blockquote":
            text = inline(child)
            if text:
                out.append(("quote", text))
        elif tag == "a" and has_block_child(child):
            # A card wrapped in a single link: keep the target, one block per card.
            text = inline(child)
            href = child.attrs.get("href", "")
            if text:
                if href and not href.startswith("#"):
                    out.append(("p", f"[{text}]({href})"))
                else:
                    out.append(("p", text))
        elif has_block_child(child):
            collect(child, out)
        else:
            text = inline(child)
            if text:
                out.append(("p", text))
    return out


def render(blocks):
    lines = []
    list_open = False
    for kind, text in blocks:
        if kind == "li":
            if not list_open:
                lines.append("")
                list_open = True
            lines.append(f"- {text}")
            continue
        if list_open:
            lines.append("")
            list_open = False
        if kind in HEADINGS:
            lines.append("")
            lines.append(f"{HEADINGS[kind]} {text}")
            lines.append("")
        elif kind == "quote":
            lines.append("")
            lines.append(f"> {text}")
            lines.append("")
        else:
            lines.append("")
            lines.append(text)
            lines.append("")
    if list_open:
        lines.append("")
    text = "\n".join(lines)
    # Collapse the runs of blank lines the block loop leaves behind.
    while "\n\n\n" in text:
        text = text.replace("\n\n\n", "\n\n")
    return text.strip() + "\n"


def build():
    parser = TreeBuilder()
    parser.feed(PAGE.read_text(encoding="utf-8"))
    main = find(parser.root, "main")
    if main is None:
        raise SystemExit("✗ index.html has no <main> element to render")
    blocks = collect(main, [])
    return HEADER + render(blocks)


def relative_links(markdown):
    """Local link targets referenced from a Markdown file."""
    links = []
    for raw in markdown.split("]("):
        if ")" not in raw:
            continue
        target = raw.split(")", 1)[0].strip().split("#", 1)[0]
        if not target or target.startswith(("http://", "https://", "mailto:", "/")):
            continue
        links.append(target)
    return links


def check(rendered, problems):
    if not FULL.is_file():
        problems.append(f"✗ {FULL.name} is missing — run python3 scripts/build_llms.py")
    elif FULL.read_text(encoding="utf-8") != rendered:
        problems.append(f"✗ {FULL.name} is stale — run npm run build")

    manifest = MANIFEST.read_text(encoding="utf-8")
    if not manifest.startswith("# "):
        problems.append(f"✗ {MANIFEST.name} must start with a single H1")
    heading = manifest.splitlines()[0][2:].strip()
    if "Mars Cruz" not in heading:
        problems.append(f"✗ {MANIFEST.name} H1 should name Mars Cruz, found {heading!r}")

    for link in sorted(set(relative_links(manifest))):
        if not (ROOT / link).is_file():
            problems.append(f"✗ {MANIFEST.name} links to missing file: {link}")

    for required in ("llms-full.txt", "facts.json", "assets/resume.pdf"):
        if required not in manifest:
            problems.append(f"✗ {MANIFEST.name} does not point agents at {required}")


def main():
    rendered = build()
    problems = []

    if "--check" in sys.argv:
        check(rendered, problems)
        if problems:
            for line in problems:
                print(line)
            print(f"{len(problems)} error(s) in the machine-readable layer")
            return 1
        print("✓ PASS — llms.txt manifest and llms-full.txt are current")
        return 0

    FULL.write_text(rendered, encoding="utf-8")
    print(f"✓ wrote {FULL.relative_to(ROOT)} ({len(rendered.splitlines())} lines)")
    check(rendered, problems)
    for line in problems:
        print(line)
    return 1 if problems else 0


if __name__ == "__main__":
    sys.exit(main())
